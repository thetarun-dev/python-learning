
# Python operators

'''

Arithmetics operators

Comparison Operators

Logical Operators

Conditional Operators

'''

# -------------------------------------------------------------------------------------
# Arithmetics

# add
print(15 + 20)

# Sub
print(15 - 20)

# Multuply
print(15 * 20)

# Divison
print(15 / 20)

# only give integer value in Divison
print(15 // 20)

# modulo => Reminder
print(15 % 20)

# power
print(5 ** 3)

# -------------------------------------------------------------------------------------
# Comparison Operators

# <
print(5 < 2)  # False

# >
print(5 > 2)  # True

# <=
print(5 <= 2) # False

# >=
print(5 >= 2) # True

# ==
print(5 == 5) # True

# !=
print(5 != 3) # True

# -------------------------------------------------------------------------------------
# Logical Operators

# and => it will show True if both statements are true, else False
print((5 == 5) and (5 >= 3))        # True
print((5 == 5) and (5 >= 6))        # False

# or => it will show False if both statements are False, else True
print((5 == 5) or (5 < 3))          # True
print((5 != 5) and (5 >= 6))        # False

# not => will change the True to False and False to True
print(not(5 == 5))                  # False
print(not(5 != 5))                  # True


