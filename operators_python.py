# -------------------------------------------------------------------------------------
# Arithmetics

# add
print(15 + 20)

# Sub
print(15 - 20)

# Multuply
print(15 * 20)

# Divison
print(15 / 20)

# only give integer value in Divison
print(15 // 20)

# modulo => Reminder
print(15 % 20)

# power
print(5 ** 3)

# -------------------------------------------------------------------------------------
# Comparison Operators

# <
print(5 < 2)  # False

# >
print(5 > 2)  # True

# <=
print(5 <= 2) # False

# >=
print(5 >= 2) # True

# ==
print(5 == 5) # True

# !=
print(5 != 3) # True

