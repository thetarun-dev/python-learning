# set 
thisset = {"apple", "banana", "cherry"}
print(thisset)

# -------------------------------------------------------------------------------------
# adding new item in a set using the add()
# even though we cannot change the value which is already store in set we can add new and remove value to the set
thisset.add("watermelon")
